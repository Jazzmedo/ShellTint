# ─── Chromium ───
# Chromium wants a service worker instead of background.scripts and has no theme
# API; sw.js imports the Firefox list, so the two can't drift apart.
chromium="$dist/chromium"
rm -rf "$chromium"
cp -r "$repo/extension" "$chromium"
CHROMIUM_KEY="$chromium_key" node - "$chromium" <<'JS'
const fs = require('fs');
const dir = process.argv[2];
const file = `${dir}/manifest.json`;
const manifest = JSON.parse(fs.readFileSync(file, 'utf8'));
const scripts = manifest.background.scripts.map(s => `'/${s}'`).join(',\n    ');
fs.writeFileSync(`${dir}/background/sw.js`, `// Generated by scripts/package.sh from manifest.json's background.scripts.\nimportScripts(\n    ${scripts},\n);\n`);
delete manifest.browser_specific_settings;
manifest.permissions = manifest.permissions.filter(p => p !== 'theme');
manifest.background = { service_worker: 'background/sw.js' };
manifest.minimum_chrome_version = '120';
manifest.key = process.env.CHROMIUM_KEY;
fs.writeFileSync(file, JSON.stringify(manifest, null, 2) + '\n');

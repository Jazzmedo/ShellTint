czip="shelltint-$version-chromium.zip"
rm -f "$dist/$czip"
(cd "$chromium" && zip -qr -X "$dist/$czip" .)
(cd "$dist" && sha256sum "$czip" > "$czip.sha256")
echo "built $chromium and $dist/$czip"
cat "$dist/$czip.sha256"
